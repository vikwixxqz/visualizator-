def log2_ceil(n):
    """Округлённый вверх логарифм по основанию 2 (для оценки высоты)."""
    return math.ceil(math.log2(n + 1)) if n > 0 else 0


def estimate(notation, sizes):
    """Подставить размеры структуры в формулу сложности.

    sizes — словарь с текущими размерами, например {"n": 6} или
    {"n": 8, "h": 3} или {"V": 5, "E": 5}.
    Возвращает строку вида «n = 6 → ≈ 6 операций».
    """
    n = sizes.get("n", 0)
    h = sizes.get("h", 0)
    v = sizes.get("V", 0)
    e = sizes.get("E", 0)

    if notation == "O(1)":
        return "не зависит от размера структуры → ≈ 1 операция"
    if notation == "O(n)":
        return f"n = {n} → ≈ {n} операций"
    if notation == "O(V²)":
        return f"V = {v} → V² = {v * v} операций"
    if notation == "O(V + E)":
        return f"V = {v}, E = {e} → V + E = {v + e} операций"
    if notation in ("O(h)", "O(n·h)"):
        # для дерева дополнительно показываем, насколько оно «хорошее»:
        # лучший случай h ≈ log2(n), худший h = n - 1 (вырожденная цепочка)
        best = max(log2_ceil(n) - 1, 0)
        if n <= 2 or h <= best:
            shape = "дерево сбалансировано, O(log n)"
        elif h >= n - 1:
            shape = "дерево выродилось в цепочку, O(n)!"
        else:
            shape = "промежуточный случай"
        if notation == "O(h)":
            return f"h = {h}, n = {n} (минимально возможная h = {best}) → {shape}"
        return f"n = {n}, h = {h} → n·h ≈ {n * max(h, 1)} операций; {shape}"
    return ""
